"""Write constraints/LFE5U-25F-7BG256I.lpf (nextpnr-ecp5 / Diamond) from design.py."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import design as D

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "constraints", "LFE5U-25F-7BG256I.lpf")
GROUPS = [("Clock", r"CLK25$"), ("CH347F UART0 + SPI", r"CH_"), ("User LEDs", r"LED"),
          ("DIP switches", r"SW\d"), ("Buttons", r"BTN"), ("7-segment", r"SEG_|DIG"), ("SDRAM", r"RAM_"),
          ("microSD", r"SD_"), ("Audio", r"AUDIO"), ("HDMI (DVI)", r"HDMI_"), ("VGA", r"VGA_"),
          ("PMOD", r"PMOD"), ("GPIO header", r"GPIO"), ("SPI flash (after config: USRMCLK drives FLASH_CLK)", r"FLASH_")]
SKIP = re.compile(r"(JTAG_.*|PROGRAMN|INITN|DONE|CFG\d)$|.*_N$")      # dedicated pins, and the _N half of LVCMOS33D pairs


def port(net):
    """GPIO12 -> gpio[12], SEG_A -> seg_a, RAM_DQ3 -> ram_dq[3]."""
    m = re.match(r"(.*?)(\d+)$", net)
    if m and not net.startswith(("HDMI", "CLK")):
        return "%s[%s]" % (m.group(1).lower().rstrip("_"), m.group(2))
    return net.lower()


def main():
    byname = {n: b for b, n in D.PINS.items()}
    lines = ["# LFE5U-25F-7BG256I emulation board - generated by tools/gen_lpf.py from tools/design.py",
             "# All banks VCCIO = 3.3 V.  Port names: gpio[0..33], led[0..7], sw[0..7], ram_dq[0..15], ...",
             "", "BLOCK RESETPATHS;", "BLOCK ASYNCPATHS;", "SYSCONFIG CONFIG_IOVOLTAGE=3.3 COMPRESS_CONFIG=ON MCCLK_FREQ=62 "
             "SLAVE_SPI_PORT=DISABLE MASTER_SPI_PORT=ENABLE SLAVE_PARALLEL_PORT=DISABLE;", ""]
    done = set()
    for title, rx in GROUPS:
        nets = sorted((n for n in byname if re.match(rx, n) and not SKIP.match(n) and n not in done),
                      key=lambda n: [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", n)])
        if not nets:
            continue
        lines.append("# ---- %s" % title)
        for n in nets:
            done.add(n)
            p = port(n)
            if n.endswith("_P"):
                p = n[:-2].lower()
            if n == "FLASH_CLK":
                lines.append("# FLASH_CLK (N9) is CCLK: reach it through the USRMCLK primitive, not as a port")
                continue
            attrs = D.IOSTD.get(n, "IO_TYPE=LVCMOS33")
            if "IO_TYPE" not in attrs:
                attrs = "IO_TYPE=LVCMOS33 " + attrs
            lines.append('LOCATE COMP "%s" SITE "%s";' % (p, byname[n]))
            lines.append('IOBUF PORT "%s" %s;' % (p, attrs))
        if title == "Clock":
            lines.append('FREQUENCY PORT "clk25" 25 MHZ;')
        lines.append("")
    left = sorted(set(byname) - done - {n for n in byname if SKIP.match(n)})
    assert not left, left
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", newline="\n").write("\n".join(lines) + "\n")
    print("wrote", os.path.normpath(OUT), sum(l.startswith("LOCATE") for l in lines), "ports")


if __name__ == "__main__":
    main()
